// The late-night note's contract (1.4 D), for moodbow-app supabase/contracts/late-note.json and
// the web's src/lib/journal/lateNote.contract.json. The expectations are worked out here from the
// rules alone, with each zone's fixed UTC offset on these November dates (no Intl), so they never
// echo either client's code.
// - show when the mood is 1 or 2 and the save's hour in the profile's zone is 0 to 4 (00:00-04:59),
//   unless the person's mark already holds that night (the save's date in that zone);
// - when it shows, the mark becomes that date; otherwise it stays as it was.
//
// node scripts/gen-late-note-contract.mjs <out.json>
import { writeFileSync } from "node:fs";

const [, , outPath] = process.argv;
const RULES = { fromHour: 0, toHour: 4, moods: [1, 2] };
// Minutes east of UTC, 15-21 November 2026 (New York is back on EST from 1 Nov; Paris on CET).
const OFFSET = { UTC: 0, "Asia/Bangkok": 7 * 60, "America/New_York": -5 * 60, "Europe/Paris": 60 };

function local(savedAt, zone) {
  const t = new Date(Date.parse(savedAt) + OFFSET[zone] * 60000);
  return { date: t.toISOString().slice(0, 10), hour: t.getUTCHours() };
}
function expect(c) {
  const { date, hour } = local(c.saved_at, c.zone);
  const show = RULES.moods.includes(c.mood) && hour >= RULES.fromHour && hour <= RULES.toHour && c.mark !== date;
  return { ...c, show, mark_after: show ? date : c.mark };
}

