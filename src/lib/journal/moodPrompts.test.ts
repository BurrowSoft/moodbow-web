import { describe, expect, it } from "vitest";
import contract from "./moodPrompts.contract.json";
import { MOOD_GROUP, moodGroup, moodPrompt, type MoodPromptInput } from "./moodPrompts";

type Case = MoodPromptInput & { name: string; expect: { source: string; group?: string; prompt?: string; help?: boolean; savedPlace?: number } };

describe("mood prompts: the contract (drafted for moodbow-app, generated by scripts/gen-mood-prompts-contract.mjs)", () => {
  it("pins the mood groups", () => {
    expect(contract.rules.moodGroup).toEqual(Object.fromEntries(Object.entries(MOOD_GROUP).map(([k, v]) => [k, v])));
  });

  for (const c of contract.cases as Case[]) {
    it(c.name, () => {
      const r = moodPrompt(c);
      const got = r.source === "none" ? { source: "none" } : { ...r, prompt: r.prompt.id };
      expect(got).toEqual(c.expect);
    });
  }
});

describe("mood prompts: guards", () => {
  it("a mood outside 1-5 is no mood", () => {
    for (const m of [0, 6, 2.5, null, undefined]) expect(moodGroup(m)).toBeNull();
  });

  it("Free never gets a second group prompt, however many times Another is pressed", () => {
    for (let a = 1; a < 40; a++) expect(moodPrompt({ today: "2026-11-18", mood: 3, flagged: false, plus: false, another: a }).source).toBe("daily");
  });
});
